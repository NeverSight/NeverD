#!/usr/bin/env python3
"""Generate include/neverd/ir/intrinsics/AArch64/AArch64SystemOperands.def.

An AArch64 MRS, MSR or SYS names its operation by an encoding: the system
register `mrs x0, cntvct_el0` reads is op0 3, op1 3, CRn 14, CRm 0, op2 2,
and `dc civac, x1` is the SYS with op1 3, CRn 7, CRm 14, op2 1.  The C
writers print an instruction a lift keeps that encoding of under the name the
listing gives it, which capstone's disassembler prints from its generated
tables.  This script copies those tables: every system register with whether
an MRS may read it and an MSR write it, every DC, IC, AT and TLBI alias of
SYS with whether it takes a register, and every PSTATE field an MSR
(immediate) writes, all by encoding.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
SOURCE = (ROOT / "third_party" / "capstone" / "arch" / "AArch64" /
          "AArch64GenSystemOperands.inc")
OUTPUT = (ROOT / "include" / "neverd" / "ir" / "intrinsics" / "AArch64" /
          "AArch64SystemOperands.def")


def table(text, element):
    """The rows of the capstone table of \\p element records."""
    match = re.search(r"static const %s \w+\[\] = \{\n(.*?)\n  \};" %
                      re.escape(element), text, re.S)
    if not match:
        sys.exit(f"no {element} table in {SOURCE}")
    return [line for line in match.group(1).splitlines()
            if line.startswith('  { "')]


def fields(row):
    """The name, encoding and flags of one row, in its order."""
    name = re.match(r'  \{ "(\w+)"', row).group(1)
    # Drop the row's closing brace and index comment, then its raw values
    # and its feature set.
    rest = re.sub(r"\s*\},?\s*//.*$", "", row[row.index(",") + 1:])
    rest = re.sub(r"\{[^{}]*\}", "", rest)
    values = [v.strip() for v in rest.split(",") if v.strip()]
    return name, values


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    text = args.source.read_text()

    lines = [
        "// The AArch64 system registers, the DC, IC, AT and TLBI aliases of",
        "// SYS and the PSTATE fields of MSR (immediate), by encoding, under",
        "// the names the listing prints.  Generated by",
        "// scripts/generate_aarch64_system_operands.py from capstone's",
        "// AArch64GenSystemOperands.inc; regenerate it rather than edit it.",
        "//",
        "// NEVERD_A64_SYSREG(Name, Encoding, Readable, Writable): a system",
        "//   register; Encoding is op0:op1:CRn:CRm:op2.  Where two share an",
        "//   encoding, the first an MRS may read, or an MSR write, is its name.",
        "// NEVERD_A64_SYS_ALIAS(Mnemonic, Name, Encoding, TakesRegister): an",
        "//   alias of SYS; Encoding is op1:CRn:CRm:op2.",
        "// NEVERD_A64_PSTATE(Name, Op1, Op2, CRmHigh, ImmediateBits): a field",
        "//   an MSR (immediate) writes.  CRm holds the immediate, or, for a",
        "//   one-bit one, CRmHigh above it.",
        "",
        "#ifndef NEVERD_A64_SYSREG",
        "#define NEVERD_A64_SYSREG(Name, Encoding, Readable, Writable)",
        "#endif",
        "#ifndef NEVERD_A64_SYS_ALIAS",
        "#define NEVERD_A64_SYS_ALIAS(Mnemonic, Name, Encoding, TakesRegister)",
        "#endif",
        "#ifndef NEVERD_A64_PSTATE",
        "#define NEVERD_A64_PSTATE(Name, Op1, Op2, CRmHigh, ImmediateBits)",
        "#endif",
        "",
    ]
    counts = {}

    def emit(kind, line):
        counts[kind] = counts.get(kind, 0) + 1
        lines.append(line)

    for row in table(text, "AArch64SysReg_SysReg"):
        name, values = fields(row)
        # "NAME", raw, encoding, readable, writeable.
        values = [v for v in values if not v.startswith('"')]
        encoding, readable, writable = values[0], values[1], values[2]
        emit("system registers",
             f'NEVERD_A64_SYSREG("{name.lower()}", {encoding}, {readable}, '
             f"{writable})")
    for mnemonic, element, has_flag in (("dc", "AArch64DC_DC", False),
                                        ("ic", "AArch64IC_IC", True),
                                        ("at", "AArch64AT_AT", False),
                                        ("tlbi", "AArch64TLBI_TLBI", True)):
        for row in table(text, element):
            name, values = fields(row)
            takes_register = values[1] if has_flag else "true"
            emit("SYS aliases",
                 f'NEVERD_A64_SYS_ALIAS("{mnemonic}", "{name.lower()}", '
                 f"{values[0]}, {takes_register})")
    for row in table(text, "AArch64PState_PStateImm0_15"):
        name, values = fields(row)
        encoding = int(values[0], 16)
        emit("PSTATE fields",
             f'NEVERD_A64_PSTATE("{name.lower()}", {encoding >> 3}, '
             f"{encoding & 7}, 0, 4)")
    for row in table(text, "AArch64PState_PStateImm0_1"):
        name, values = fields(row)
        encoding = int(values[0], 16)
        emit("PSTATE fields",
             f'NEVERD_A64_PSTATE("{name.lower()}", {(encoding >> 3) & 7}, '
             f"{encoding & 7}, {encoding >> 6}, 1)")
    for row in table(text, "AArch64SVCR_SVCR"):
        # MSR SVCR<field>, #imm is op1 3, op2 3, CRm <field>:imm.
        name, values = fields(row)
        emit("PSTATE fields",
             f'NEVERD_A64_PSTATE("{name.lower()}", 3, 3, '
             f"{int(values[0], 16)}, 1)")

    lines += [
        "",
        "#undef NEVERD_A64_SYSREG",
        "#undef NEVERD_A64_SYS_ALIAS",
        "#undef NEVERD_A64_PSTATE",
    ]
    args.output.write_text("\n".join(lines) + "\n")
    print(", ".join(f"{n} {kind}" for kind, n in counts.items()),
          file=sys.stderr)


if __name__ == "__main__":
    main()
