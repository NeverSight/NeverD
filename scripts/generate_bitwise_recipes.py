#!/usr/bin/env python3
"""Regenerate the complete optimal recipes for zero through three inputs."""

import argparse
from pathlib import Path
import subprocess


def recipes(arity):
    mask = (1 << (1 << arity)) - 1
    costs = [1 << 30] * (mask + 1)
    operations = costs.copy()
    result = [None] * (mask + 1)
    changed = False

    def relax(table, cost, count, recipe):
        nonlocal changed
        if (cost, count) >= (costs[table], operations[table]):
            return
        costs[table], operations[table], result[table] = cost, count, recipe
        changed = True

    relax(0, 1, 0, ("Zero", 0, 0))
    relax(mask, 1, 0, ("Ones", 0, 0))
    for axis in range(arity):
        table = sum(1 << corner for corner in range(1 << arity)
                    if corner & (1 << axis))
        relax(table, 1, 0, ("Atom", axis, 0))
    while changed:
        changed = False
        for left in range(mask + 1):
            if result[left] is None:
                continue
            relax(left ^ mask, costs[left] + 1, operations[left] + 1,
                  ("Not", left, 0))
            for right in range(left + 1, mask + 1):
                if result[right] is None:
                    continue
                cost = costs[left] + costs[right] + 1
                count = operations[left] + operations[right] + 1
                for kind, table in (("And", left & right),
                                    ("Or", left | right),
                                    ("Xor", left ^ right)):
                    relax(table, cost, count, (kind, left, right))
    assert all(value is not None for value in result)
    return result, max(costs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang-format", default="clang-format")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = [
        "//===- SymBitwiseRecipes.inc - Complete small Boolean recipes --------===//",
        "//",
        "// NeverD Decompiler",
        "//",
        "//===----------------------------------------------------------------------===//",
        "/// \\file",
        "/// Generated by scripts/generate_bitwise_recipes.py. Do not edit by hand.",
        "/// Included after Recipe; all truth tables through three inputs are covered.",
        "",
    ]
    maximums = []
    for arity in range(4):
        table, maximum = recipes(arity)
        maximums.append(maximum)
        lines.append(f"constexpr Recipe SmallRecipes{arity}[] = {{")
        lines += [f"    {{Recipe::{kind}, {left}, {right}}},"
                  for kind, left, right in table]
        lines.append("};\n")
    lines += ["constexpr unsigned SmallRecipeMaxNodes[] = {" +
              ", ".join(map(str, maximums)) + "};", ""]
    root = Path(__file__).resolve().parents[1]
    target = root / "lib/symbolic/mba/SymBitwiseRecipes.inc"
    formatted = subprocess.run(
        [args.clang_format, "--style=file", f"--assume-filename={target}"],
        input="\n".join(lines), text=True, capture_output=True, check=True,
        cwd=root,
    ).stdout
    if args.check:
        if target.read_text() != formatted:
            raise SystemExit(f"{target} needs regeneration")
    else:
        target.write_text(formatted)


if __name__ == "__main__":
    main()
