#!/usr/bin/env python3
"""Generate closed scan ID mappings from the pinned iced source."""
import argparse
from pathlib import Path
import re

# ID equality alone admits no encoding: X86IcedScan also bounds prefixes and
# the iced decoder checks every operand. Missing/new codes retain Capstone.
VECTOR_FAMILIES = {
    "Vmovaps",
    "Vmovups",
    "Vmovapd",
    "Vmovupd",
    "Vmovss",
    "Vmovsd",
    "Vxorps",
    "Vxorpd",
    "Vfmadd132ps",
    "Vfmadd213ps",
    "Vfmadd231ps",
    "Vfmadd132pd",
    "Vfmadd213pd",
    "Vfmadd231pd",
}

LEGACY_VECTOR_FAMILIES = {
    "Movaps", "Movups", "Movapd", "Movupd", "Movss", "Movsd", "Movdqa",
    "Movdqu", "Xorps", "Xorpd", "Pxor",
}

# The batch map marks prefix-sensitive control transfers explicitly. MOVSXD
# forms other than r64/rm32, loop counters, far transfers, moffs and MPX retain
# Capstone. Code
# names retain operand/encoding distinctions; mnemonic matching alone is not
# a compatibility proof. Both maps are checked against the pinned fixtures.
SCALAR_FAMILIES = set(
    "Add Adc Sub Sbb And Or Xor Cmp Test Mov Movzx Movsx Lea Push Pop Inc Dec "
    "Neg Not Imul Mul Div Idiv Shl Shr Sar Sal Rol Ror Rcl Rcr Shld Shrd Xchg "
    "Nop Call Jmp Jo Jno Jb Jae Je Jne Jbe Ja Js Jns Jp Jnp Jl Jge Jle Jg "
    "Cmovo Cmovno Cmovb Cmovae Cmove Cmovne Cmovbe Cmova Cmovs Cmovns Cmovp "
    "Cmovnp Cmovl Cmovge Cmovle Cmovg Seto Setno Setb Setae Sete Setne Setbe "
    "Seta Sets Setns Setp Setnp Setl Setge Setle Setg Cbw Cwde Cdqe Cwd Cdq Cqo "
    "Int3 Leave Retnw Retnd Retnq".split()
)


def scalar_id(name):
    family = name.split("_")[0]
    if family in LEGACY_VECTOR_FAMILIES and "xmm" in name:
        return "X86_INS_" + family.upper()
    if name == "Movsxd_r64_rm32":
        return "X86_INS_MOVSXD"
    # iced encodes stack/operand widths in these mnemonic names as well as
    # in operand suffixes. Keep the exact encodings in the generated map.
    for base in ("Push", "Pop", "Nop", "Leave"):
        if family in {base + width for width in "wdq"}:
            family = base
            break
    if family not in SCALAR_FAMILIES or "moffs" in name:
        return "0"
    if family in {"Call", "Jmp"} and ("_ptr16" in name or "_m16" in name):
        return "0"
    if name == "Mov_r64_imm64":
        return "X86_INS_MOVABS"
    return "X86_INS_" + ("RET" if family.startswith("Retn") else family.upper())


def prefix_sensitive(name):
    family = name.split("_")[0]
    return family.startswith("J") or family in {
        "Call", "Retnw", "Retnd", "Retnq", "Int3",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("iced", type=Path)
    parser.add_argument("capstone", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    codes = re.findall(r"^\s*(\w+) = (\d+),$", args.iced.read_text(), re.M)
    if not codes or codes[0] != ("INVALID", "0"):
        raise ValueError("iced Code table must begin with INVALID = 0")
    if not all(int(index) == n for n, (_, index) in enumerate(codes)):
        raise ValueError("iced Code table must have contiguous discriminants")
    headers = args.capstone.read_text()
    ids = ["0"] * (max(int(i) for _, i in codes) + 1)
    batch_ids = [scalar_id(name) for name, _ in codes]
    count = 0
    for name, index in codes:
        parts = name.split("_")
        if parts[0] not in {"VEX", "EVEX"} or parts[1] not in VECTOR_FAMILIES:
            continue
        identifier = parts[1].upper()
        identifier = "X86_INS_" + identifier
        if not re.search(r"\b" + identifier + r"\b", headers):
            raise ValueError(f"Capstone has no public ID for {identifier}")
        ids[int(index)] = identifier
        batch_ids[int(index)] = identifier
        count += 1
    for identifier in set(batch_ids) - {"0"}:
        if not re.search(r"\b" + identifier + r"\b", headers):
            raise ValueError(f"Capstone has no public ID for {identifier}")
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(
        "// Generated by generate_iced_capstone_map.py; do not edit.\n"
        "inline constexpr uint16_t InstructionIds[] = {\n"
        + "".join(
            "  " + value + ", // " + name + "\n" for (name, i), value in zip(codes, ids)
        )
        + "};\n"
        + "inline constexpr uint16_t BatchInstructionIds[] = {\n"
        + "".join(
            "  " + value
            + (" | ICED_CAPSTONE_BATCH_PREFIX_SENSITIVE"
               if value != "0" and prefix_sensitive(name) else "")
            + ", // " + name + "\n"
            for (name, i), value in zip(codes, batch_ids)
        )
        + "};\n"
    )
    print(f"Mapped {count} of {len(codes)} iced codes; other codes fall back")
    print(f"Batch map admits {sum(value != '0' for value in batch_ids)} codes")


if __name__ == "__main__":
    main()
