#!/usr/bin/env python3
"""Generate include/neverd/libc/MinGWHeaderFunctions.inc.

A whole-module C unit for a Windows program includes the C runtime headers
its library calls need, and those of mingw-w64 declare many routines that
glibc's do not: `__mingw_printf`, `_lock_file`, `_onexit`.  A MinGW program
links its own copies of some of them, and the unit cannot define a function
under a name a header it includes declares otherwise.  This script lists the
functions the mingw-w64 headers declare, for every header the C writers can
include (the registry in lib/libc/LibCNames.cpp, plus <excpt.h> and
<intrin.h>) that compiles for the target, from clang's JSON AST of them.
Only the names are read, and only from the mingw-w64 headers themselves, not
the compiler's.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parent.parent
HEADERS = ROOT / "include" / "neverd" / "libc"
OUTPUT = HEADERS / "MinGWHeaderFunctions.inc"
DEFAULT_TARGET = "x86_64-w64-mingw32"
# The headers the writers include for a Windows program besides the C
# library's: those its exception filters and its intrinsics name.
WINDOWS_HEADERS = ("excpt.h", "intrin.h")
# A whole translation unit of these headers dumps to tens of MiB of JSON.
MAX_AST_BYTES = 512 * 1024 * 1024
TIMEOUT_SECONDS = 600


def registry_headers():
    """Every header a kXHeader constant of the libc headers names."""
    headers = set()
    for path in sorted(HEADERS.rglob("*.h")):
        headers.update(re.findall(
            r'inline constexpr std::string_view k\w+Header = "([^"]+)";',
            path.read_text()))
    return sorted(headers)


def compiles(clang, target, header, scratch):
    source = scratch / "probe.c"
    source.write_text(f"#include <{header}>\n")
    result = subprocess.run(
        [clang, "-target", target, "-fsyntax-only", "-w", str(source)],
        capture_output=True, timeout=TIMEOUT_SECONDS)
    return result.returncode == 0


def include_directory(clang, target, scratch):
    """The directory the target's <stdio.h> is found in."""
    source = scratch / "where.c"
    source.write_text("#include <stdio.h>\n")
    result = subprocess.run(
        [clang, "-target", target, "-M", str(source)],
        capture_output=True, text=True, timeout=TIMEOUT_SECONDS)
    for word in result.stdout.replace("\\\n", " ").split():
        if word.endswith("/stdio.h"):
            return str(Path(word).resolve().parent)
    sys.exit(f"cannot find the {target} headers")


def declared_functions(clang, target, headers, scratch, directory):
    """The functions a header under \\p directory declares."""
    source = scratch / "headers.c"
    source.write_text("".join(f"#include <{h}>\n" for h in headers))
    result = subprocess.run(
        [clang, "-target", target, "-fsyntax-only", "-w", "-Xclang",
         "-ast-dump=json", str(source)],
        capture_output=True, timeout=TIMEOUT_SECONDS)
    if result.returncode != 0:
        sys.exit(result.stderr.decode(errors="replace"))
    if len(result.stdout) > MAX_AST_BYTES:
        sys.exit("the header AST is larger than expected")
    names = set()
    # The JSON AST names a declaration's file only where it changes.
    current = None
    for decl in json.loads(result.stdout).get("inner", []):
        loc = decl.get("loc", {})
        for where in (loc, loc.get("spellingLoc", {}),
                      loc.get("expansionLoc", {})):
            if "file" in where:
                current = str(Path(where["file"]).resolve())
                break
        if decl.get("kind") != "FunctionDecl" or decl.get("isImplicit"):
            continue
        if decl.get("name") and current and current.startswith(
                directory + "/"):
            names.add(decl["name"])
    return names


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--clang", default="clang")
    parser.add_argument("--target", default=DEFAULT_TARGET)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as directory:
        scratch = Path(directory)
        headers = [h for h in [*registry_headers(), *WINDOWS_HEADERS]
                   if compiles(args.clang, args.target, h, scratch)]
        names = declared_functions(
            args.clang, args.target, headers, scratch,
            include_directory(args.clang, args.target, scratch))

    lines = [
        "// Functions the mingw-w64 headers declare, which a whole-module C",
        "// unit for a Windows program cannot define under their names: those",
        "// of every header the C writers can include that compiles for",
        f"// {args.target}.  Generated by",
        "// scripts/generate_mingw_header_functions.py from the mingw-w64",
        "// headers; regenerate it rather than edit it.  Included by",
        "// MinGWHeaderFunctions.cpp with NEVERD_MINGW_HEADER_FUNCTION defined.",
        "",
        *(f'NEVERD_MINGW_HEADER_FUNCTION("{name}")' for name in sorted(names)),
    ]
    args.output.write_text("\n".join(lines) + "\n")
    print(f"{len(names)} functions from {len(headers)} headers",
          file=sys.stderr)


if __name__ == "__main__":
    main()
