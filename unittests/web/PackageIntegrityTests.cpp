TEST(WebPackageIntegrity, StrongestAlgorithmAndAnyEqualStrengthCandidate) {
  const auto A = artifact("abc");
  const auto Good = sri("sha512", ABC512);
  const auto Wrong = sri("sha512", std::string(128, '0'));
  for (const auto &S : {sri("sha256", ABC256), sri("sha384", ABC384), Good,
                        std::string("sha1-qZk+NkcGgWq6PiVxeFDCbJzQ2J0=")})
    EXPECT_EQ(verify(A, S).Status, "match");
  EXPECT_EQ(verify(A, sri("sha256", ABC256) + " " + Wrong).Status, "mismatch");
  EXPECT_EQ(verify(A, Wrong + " " + Good).Status, "match");
  EXPECT_EQ(verify(A, Good + " " + Wrong).Status, "match");
  EXPECT_EQ(verify(A, Good + " " + sri("sha256", ABC256)).Algorithm, "sha512");
  EXPECT_EQ(verify(A, Good + " " + Wrong).CandidateCount, 2);
  EXPECT_EQ(verify(A, "md5-AAAA " + Good).Status, "match");
  EXPECT_EQ(verify(A, Good + " sha512-malformed").Status, "invalid");
}

TEST(WebPackageIntegrity, UnsupportedInvalidMissingAndGitStayDistinct) {
  const auto A = artifact("abc");
  for (const auto &S : {"", " ", "-AAAA", "sha256-", "sha512-AAAA",
                        "sha1-qZk+NkcGgWq6PiVxeFDCbJzQ2J1=",
                        "sha1-qZk+NkcGgWq6PiVxeFDCbJzQ2J0", "sha!1-AAAA"})
    EXPECT_EQ(verify(A, S).Status, "invalid");
  EXPECT_EQ(verify(A, "md5-AAAA").Status, "unsupported_algorithm");
  EXPECT_EQ(verify(A, sri("sha512", ABC512) + "?x").Status,
            "unsupported_sri_options");
  std::string Huge;
  for (unsigned I = 0; I < 257; ++I)
    Huge += sri("sha256", ABC256) + " ";
  EXPECT_EQ(verify(A, Huge).Status, "integrity_declaration_budget_exceeded");
  const auto Empty = registryPackageIntegrity(artifact(R"({"dist":{}})"));
  EXPECT_EQ(verifyPackageIntegrity(A, Empty).Status, "missing_declaration");
  auto Git = Empty;
  Git.Git = true;
  Git.Value = std::string(40, 'a');
  EXPECT_EQ(verifyPackageIntegrity(A, Git).Status,
            "git_commit_declared_unverified");
  Git.Git = false;
  EXPECT_EQ(verifyPackageIntegrity(A, Git).Status, "invalid");
  for (const auto *JSON : {R"({"dist":{"integrity":42}})", R"({"dist":null})",
                           R"({"dist":{"integrity":"x","integrity":"y"}})"})
    EXPECT_THROW(registryPackageIntegrity(artifact(JSON)), Error);
}

TEST(WebPackageIntegrity, DigestIsOverOriginalGzipNotExpandedTarOrMembers) {
  const auto Tar = test::finishTar(test::tarMember("package/a", "abc"));
  const auto Original = artifact(test::storedGzip(Tar));
  llvm::SHA256 H;
  H.update(Tar);
  const auto ExpandedSRI = "sha256-" + llvm::encodeBase64(H.final());
  EXPECT_EQ(verify(Original, ExpandedSRI).Status, "mismatch");
  EXPECT_EQ(verify(Original, sri("sha256", ABC256)).Status, "mismatch");
  const auto R = verify(Original, sri("sha256", Original.BlobHash));
  EXPECT_EQ(R.Status, "match");
  EXPECT_EQ(R.BlobHash, Original.BlobHash);
  EXPECT_EQ(R.Bytes, Original.Content.size());
  auto CorruptIdentity = Original;
  CorruptIdentity.BlobHash = std::string(64, '0');
  EXPECT_THROW(verify(CorruptIdentity, sri("sha256", Original.BlobHash)),
               Error);
}

TEST(WebPackageIntegrity, LockSelectionRetainsItsExactDeclarationAndGitStatus) {
  PackageAnalysis A;
  A.Kind = "npm-lock";
  A.ArtifactID = "lock";
  A.BlobHash = "captured-lock-hash";
  PackageInstance P;
  P.ID = "package";
  P.Integrity = sri("sha512", ABC512);
  P.IntegrityStatus = packageIntegrityDeclarationStatus(*P.Integrity);
  A.Packages.push_back(P);
  const auto D = lockedPackageIntegrity(A, P.ID);
  EXPECT_EQ(D.ArtifactID, A.ArtifactID);
  EXPECT_EQ(D.SelectionID, P.ID);
  EXPECT_EQ(verifyPackageIntegrity(artifact("abc"), D).Status, "match");
  EXPECT_THROW(lockedPackageIntegrity(A, "other"), Error);
  A.Packages[0].Integrity.reset();
  A.Packages[0].IntegrityStatus = "invalid";
  EXPECT_EQ(
      verifyPackageIntegrity(artifact("abc"), lockedPackageIntegrity(A, P.ID))
          .Status,
      "invalid");
  A.Kind = "package-json";
  EXPECT_THROW(lockedPackageIntegrity(A, P.ID), Error);
}

TEST(WebPackageIntegrity, OfficialClaudeCodeTarballsWhenSupplied) {
  const auto *Directory = std::getenv("NEVERD_CLAUDE_CODE_21296_NPM_DIR");
  if (!Directory)
    GTEST_SKIP()
        << "Official pinned npm originals and registry snapshots not supplied";
  struct Expected {
    const char *Name, *SRI, *SHA256;
    uint64_t Bytes;
  };
  const Expected Cases[]{
      {"claude-code-2.1.296",
       "sha512-OX/k/rpcthMqnFKOWcpNcbiLsMKtAjLOpQNJHlYiDCFUznWCIwdRTyl/"
       "p9SdHVrsrzZuPMCNqZjnpakIni6upw==",
       "f6c375d51d4c22a7a850e185a0d7ddda85173f89dbbeb3262aa7971e3bd670b5",
       29001},
      {"claude-code-linux-x64-2.1.296",
       "sha512-+m01urgelnI+VJxPaKPEK0wixgq42uZ8PeCaUk5tX/8YoDBvSmC/"
       "REVQG2jQfJAr8dxunpjJ600FvLrcj1WWTw==",
       "eef5a2e2b09a5e7d2ce784d1b3ba335ae7fc6c7f6256c802a0ebf2c21e4fd0e1",
       114864541}};
  for (const auto &C : Cases) {
    const auto Base = std::string(Directory) + "/" + C.Name;
    const auto Original = capture(Base + ".tgz", Limits{});
    const auto Metadata = capture(Base + ".registry.json", Limits{});
    const auto &A = Original.Artifacts.front();
    ASSERT_EQ(A.BlobHash, C.SHA256);
    ASSERT_EQ(A.Content.size(), C.Bytes);
    const auto D = registryPackageIntegrity(Metadata.Artifacts.front());
    ASSERT_EQ(D.Value, C.SRI);
    const auto R = verifyPackageIntegrity(A, D);
    EXPECT_EQ(R.Status, "match");
    EXPECT_EQ(R.Algorithm, "sha512");
  }
}
