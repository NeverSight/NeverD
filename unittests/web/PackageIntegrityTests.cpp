constexpr std::string_view ABC512 =
    "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a"
    "2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f";
constexpr std::string_view ABC384 =
    "cb00753f45a35e8bb5a03d699ac65007272c32ab0eded1631a8b605a43ff5bed"
    "8086072ba1e7cc2358baeca134c825a7";
constexpr std::string_view ABC256 =
    "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad";
std::string sri(std::string_view Algorithm, std::string_view Hex) {
  return std::string(Algorithm) + "-" + llvm::encodeBase64(llvm::fromHex(Hex));
}
Artifact artifact(std::string_view Bytes) {
  BlobStore S(Limits::HardInputBytes);
  S.append(Bytes);
  S.seal();
  Artifact A;
  A.Content = S.whole();
  A.BlobHash = A.Content.digest();
  A.ID = identity("integrity-test", {A.BlobHash});
  return A;
}
PackageIntegrityResult verify(const Artifact &A, const std::string &SRI) {
  const auto M = artifact("{\"dist\":{\"integrity\":\"" + SRI + "\"}}");
  return verifyPackageIntegrity(A, registryPackageIntegrity(M));
}

TEST(WebPackageDigest, StandardVectorsAcrossChunkAndPaddingBoundaries) {
  const std::string Long =
      "abcdefghbcdefghicdefghijdefghijkefghijklfghijklmghijklmn"
      "hijklmnoijklmnopjklmnopqklmnopqrlmnopqrsmnopqrstnopqrstu";
  struct Vector {
    std::string Message, SHA384, SHA512;
  };
  // FIPS algorithm examples / RFC 6234 test vectors, not generated by NeverD.
  const Vector Vectors[]{
      {"",
       "38b060a751ac96384cd9327eb1b1e36a21fdb71114be07434c0cc7bf"
       "63f6e1da274edebfe76f65fbd51ad2f14898b95b",
       "cf83e1357eefb8bdf1542850d66d8007d620e4050b5715dc83f4a921d36ce9ce"
       "47d0d13c5d85f2b0ff8318d2877eec2f63b931bd47417a81a538327af927da3e"},
      {"abc", std::string(ABC384), std::string(ABC512)},
      {Long,
       "09330c33f71147e83d192fc782cd1b4753111b173b3b05d22fa08086e3b0f712"
       "fcc7c71a557e2db966c3e9fa91746039",
       "8e959b75dae313da8cf4f72814fc143f8f7779c6eb9f7fa17299aeadb6889018"
       "501d289e4900f7e4331b99dec4b5433ac7d329eeb6dd26545e96e55b874be909"},
      {std::string(1000000, 'a'),
       "9d0e1809716474cb086e834e310a4a1ced149e9c00f248527972cec5704c2a5b0"
       "7b8b3dc38ecc4ebae97ddd87f3d8985",
       "e718483d0ce769644e2e42c7bc15b4638e1f98b13b2044285632a803afa973eb"
       "de0ff244877ea60a4cb0432ce577c31beb009c5c2c49aa2e4eadb217ad8cc09b"}};
  for (const auto &V : Vectors)
    for (const size_t Chunk : {1, 17, 111, 128, 129, 65536})
      for (const bool Short : {false, true}) {
        SHA512 H(Short);
        for (size_t I = 0; I < V.Message.size(); I += Chunk)
          H.update(std::string_view(V.Message).substr(I, Chunk));
        const auto Expected = Short ? V.SHA384 : V.SHA512;
        EXPECT_EQ(llvm::toHex(H.result(), true), Expected);
        EXPECT_EQ(llvm::toHex(H.result(), true), Expected);
        H.update("");
        EXPECT_EQ(llvm::toHex(H.result(), true), Expected);
      }
}

