#!/usr/bin/env python3
"""Replay n32/n64 complex returns and direct/indirect scalar-input calls.

GCC and Clang independently produce the original objects at O0/O2, for both
byte orders. With --neverd, each selected function is regenerated by HighC and
LLVMC and linked with the other original objects. Rebuilt functions therefore
must agree with the native convention, not only with one another. Complex
parameters, variadic calls and compressed code are outside this fixture.
"""

import argparse
import io
import json
import random
from pathlib import Path

from elftools.elf.elffile import ELFFile
from unicorn import UC_HOOK_CODE
from unicorn import mips_const as mips

import roundtrip
from mips_validation_artifacts import MIPSValidationArtifacts, digest


FUNCTIONS = ('complex_result', 'direct_result', 'indirect_result')
MEMORY_RUNTIME = Path(__file__).with_name('mips-source-memory-runtime.c')


def observe(image, little, n32, width, values, function):
    uc, entry = roundtrip.emulator(
        image, 64, little, function,
        cpu_model=mips.UC_CPU_MIPS64_MIPS64R2_GENERIC)
    elf = ELFFile(io.BytesIO(image.read_bytes()))
    symbols = {s.name: s['st_value']
               for s in elf.get_section_by_name('.symtab').iter_symbols()}
    callee = symbols['complex_result']
    uc.reg_write(mips.UC_MIPS_REG_CP0_STATUS,
                 uc.reg_read(mips.UC_MIPS_REG_CP0_STATUS) | 0x24000000)
    preserved_gprs = {r: 0x7139521700000000 + r
                      for r in (*range(16, 24), 28, 30)}
    preserved_fprs = {r: 0x3ff013579bdf0000 + r
                      for r in (range(20, 32, 2) if n32 else range(24, 32))}
    mask = (1 << (width * 8)) - 1
    observations = []
    visits = []
    hook = uc.hook_add(UC_HOOK_CODE,
                       lambda uc, pc, size, _: visits.append(pc),
                       begin=callee, end=callee)
    try:
        for real, imaginary in values:
            for r in range(1, 32):
                uc.reg_write(getattr(mips, f'UC_MIPS_REG_{r}'),
                             preserved_gprs.get(r, 0x5a00000000000000 + r))
            for r in range(32):
                uc.reg_write(getattr(mips, f'UC_MIPS_REG_F{r}'),
                             preserved_fprs.get(r, 0xa500000000000000 + r))
            uc.mem_write(roundtrip.STACK - 8192, bytes([0xcc]) * 16384)
            uc.reg_write(mips.UC_MIPS_REG_SP, roundtrip.STACK)
            uc.reg_write(mips.UC_MIPS_REG_RA, roundtrip.STOP)
            uc.reg_write(mips.UC_MIPS_REG_F12, real)
            uc.reg_write(mips.UC_MIPS_REG_F13, imaginary)
            uc.reg_write(mips.UC_MIPS_REG_6, callee)
            uc.reg_write(mips.UC_MIPS_REG_FCSR, 0)
            visits.clear()
            uc.emu_start(entry, roundtrip.STOP, count=10000)
            actual = tuple(uc.reg_read(getattr(mips, f'UC_MIPS_REG_F{r}')) & mask
                           for r in (0, 2))
            context = (str(image), function, real, imaginary)
            assert actual == (real, imaginary), (context, actual)
            assert visits == [callee], (context, visits)
            assert uc.reg_read(mips.UC_MIPS_REG_PC) == roundtrip.STOP, context
            assert uc.reg_read(mips.UC_MIPS_REG_RA) == roundtrip.STOP, context
            assert uc.reg_read(mips.UC_MIPS_REG_SP) == roundtrip.STACK, context
            assert uc.reg_read(mips.UC_MIPS_REG_FCSR) == 0, context
            for r, value in preserved_gprs.items():
                assert uc.reg_read(getattr(mips, f'UC_MIPS_REG_{r}')) == value, (context, r)
            for r, value in preserved_fprs.items():
                assert uc.reg_read(getattr(mips, f'UC_MIPS_REG_F{r}')) == value, (context, r)
            observations.append([hex(x) for x in actual])
    finally:
        uc.hook_del(hook)
    return observations


def run(args, artifacts):
    rows = []
    rng = random.Random(0x4e333243)
    log = artifacts.work / 'command.log'

    def command(argv):
        roundtrip.run_command(artifacts, argv, log)

    for width in args.component_bytes or (4, 8):
        scalar = 'float' if width == 4 else 'double'
        patterns = ([0, 1, 0x80000000, 0x7f800000, 0xff800000, 0x7fa12345,
                     0xffc54321, 0xffffffff] if width == 4 else
                    [0, 1, 0x8000000000000000, 0x7ff0000000000000,
                     0xfff0000000000000, 0x7ff123456789abcd,
                     0xfff8abcdef123456, 0xffffffffffffffff])
        values = [(patterns[i], patterns[(i + 3) % len(patterns)])
                  for i in range(len(patterns))]
        values += [(rng.getrandbits(width * 8), rng.getrandbits(width * 8))
                   for _ in range(24)]
        result = f'_Complex {scalar}'
        parameters = f'{scalar} real, {scalar} imaginary'
        callback = f'{result} (*callee)({scalar}, {scalar})'
        declarations = (f'{result} complex_result({parameters});\n'
                        f'{result} direct_result({parameters});\n'
                        f'{result} indirect_result({parameters}, {callback});\n')
        texts = {
            'complex_result': f'{result} complex_result({parameters}) {{\n'
                              '  return __builtin_complex(real, imaginary);\n}\n',
            'direct_result': f'{result} direct_result({parameters}) {{\n'
                             '  return complex_result(real, imaginary);\n}\n',
            'indirect_result': f'{result} indirect_result({parameters}, {callback}) {{\n'
                               '  return callee(real, imaginary);\n}\n',
        }
        for abi in args.abi or ('n32', '64'):
            for byte_order in args.endian or ('be', 'le'):
                little = byte_order == 'le'
                endian = '-EL' if little else '-EB'
                triple = 'mips64el-linux-gnu' if little else 'mips64-linux-gnu'
                emulation = (('elf32ltsmipn32' if little else 'elf32btsmipn32')
                             if abi == 'n32' else
                             ('elf64ltsmip' if little else 'elf64btsmip'))
                common = ['-march=mips64r2', '-mabi=' + abi, '-mfp64',
                          '-mhard-float', '-mno-abicalls', '-fno-pic', '-G0',
                          '-ffreestanding', '-fno-stack-protector',
                          '-fno-unwind-tables', '-fno-asynchronous-unwind-tables']
                compilers = {'clang': args.clang, 'gcc': args.gcc}
                for original_compiler in args.original_compiler or compilers:
                    for optimization in ('-O0', '-O2'):
                        profile = (f'{abi}-{"le" if little else "be"}-{scalar}-'
                                   f'{original_compiler}-{optimization[1:]}')
                        folder = artifacts.work / profile
                        folder.mkdir()

                        def build(name, source, obj, opt):
                            assembly = obj.with_suffix('.s')
                            target = (['--target=' + triple, '-fno-addrsig']
                                      if name == 'clang' else [endian])
                            command([compilers[name], *target, *common, opt,
                                     '-S', source, '-o', assembly])
                            artifacts.keep_source(assembly)
                            command([args.assembler, '-march=mips64r2',
                                     '-mabi=' + abi, '-mfp64', endian,
                                     assembly, '-o', obj])
                            artifacts.discard(assembly)

                        def link(objects, image):
                            command([args.ld, '-m', emulation, '-Ttext', '0x10000',
                                     '-e', 'complex_result', *objects, '-o', image])

                        objects = {}
                        for function, text in texts.items():
                            source, obj = (folder / (function + suffix)
                                           for suffix in ('.c', '.o'))
                            source.write_text(declarations + text)
                            artifacts.keep_source(source)
                            build(original_compiler, source, obj, optimization)
                            objects[function] = obj
                            artifacts.discard(source)
                        runtime = folder / 'memory.o'
                        runtime_source = folder / 'memory.c'
                        runtime_source.write_text(MEMORY_RUNTIME.read_text())
                        artifacts.keep_source(runtime_source)
                        build(original_compiler, runtime_source, runtime, '-O2')
                        artifacts.discard(runtime_source)
                        original = folder / 'original.elf'
                        link([*objects.values(), runtime], original)
                        original_hash = digest(original)
                        for function in FUNCTIONS:
                            observed = observe(original, little, abi == 'n32',
                                               width, values, function)
                            rows.append({'profile': profile, 'function': function,
                                         'route': 'original', 'image_sha256': original_hash,
                                         'inputs': [[hex(a), hex(b)] for a, b in values],
                                         'outputs': observed})
                            artifacts.write('observations.json', rows)
                        if args.neverd:
                            declaration = folder / 'declarations.h'
                            declaration.write_text(declarations)
                            artifacts.keep_source(declaration)
                            command([args.neverd, 'types', original, '--declare',
                                     declaration, '--save'])
                            artifacts.discard(declaration)
                            for function in FUNCTIONS:
                                for route in ('highc', 'llvmc'):
                                    source = folder / f'{function}-{route}.c'
                                    command([args.neverd, 'decompile', original,
                                             '--func', function,
                                             *(['--llvm'] if route == 'llvmc' else []),
                                             '-o', source])
                                    artifacts.keep_source(source)
                                    source_hash = digest(source)
                                    for name in compilers:
                                        for opt in ('-O0', '-O2'):
                                            obj, image = (folder / n for n in
                                                          ('rebuilt.o', 'rebuilt.elf'))
                                            build(name, source, obj, opt)
                                            link([obj if f == function else original_obj
                                                  for f, original_obj in objects.items()]
                                                 + [runtime], image)
                                            observed = observe(image, little, abi == 'n32',
                                                               width, values, function)
                                            rows.append({'profile': profile, 'function': function,
                                                         'route': route, 'compiler': name,
                                                         'optimization': opt,
                                                         'original_sha256': original_hash,
                                                         'source_sha256': source_hash,
                                                         'image_sha256': digest(image),
                                                         'outputs': observed})
                                            artifacts.write('observations.json', rows)
                                            artifacts.discard(obj, image)
                                    artifacts.discard(source)
                        artifacts.discard(*objects.values(), runtime, original)
    originals = [row for row in rows if row['route'] == 'original']
    rebuilt = [row for row in rows if row['route'] != 'original']
    summary = {'original_images': len(originals) // len(FUNCTIONS),
               'original_executions': sum(len(row['outputs']) for row in originals),
               'rebuilt_images': len(rebuilt),
               'rebuilt_executions': sum(len(row['outputs']) for row in rebuilt),
               'driver_sha256': digest(Path(__file__))}
    artifacts.write('summary.json', summary)
    print(json.dumps(summary))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('clang', 'gcc', 'assembler', 'ld', 'output'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--neverd', type=Path)
    parser.add_argument('--abi', action='append', choices=('n32', '64'))
    parser.add_argument('--endian', action='append', choices=('be', 'le'))
    parser.add_argument('--component-bytes', type=int, action='append', choices=(4, 8))
    parser.add_argument('--original-compiler', action='append', choices=('clang', 'gcc'))
    args = parser.parse_args()
    with MIPSValidationArtifacts(
            args.output, 'n32-n64-complex-roundtrip',
            (args.clang, args.gcc, args.assembler, args.ld, MEMORY_RUNTIME,
             *([args.neverd] if args.neverd else []))) as artifacts:
        run(args, artifacts)


if __name__ == '__main__':
    main()
